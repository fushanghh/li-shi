HAIR = (0.05, 0.04, 0.035)

def _cape_side(c, t, col, dark, wind, a, flat=0):
    w = math.sin(t * 2.8) * 40 * wind; w2 = math.sin(t * 2.8 + 1.3) * 60 * wind
    pts = [(-20, -780), (-200, -720, -380 - w, -560, -560 - w2, -320 + flat),
           (-640 - w2, -200 + flat), (-560 - w * 0.6, -150 + flat), (-470 - w2 * 0.5, -120 + flat),
           (-330, -200, -180, -380, -70, -560)]
    shape(c, pts, col, 5, LINE, a)
    hatch(c, [(-20, -780), (-380 - w, -560), (-640 - w2, -200 + flat), (-470 - w2 * 0.5, -120 + flat), (-260, -380)],
          a, gap=10, col=(0.2, 0, 0), alpha=0.4)
    for k in range(3):
        x1 = -300 - k * 100
        line(c, [(-60, -740 + k * 20), (-180 - k * 40, -600, x1 - w * 0.6, -420, x1 - 120 - w2 * 0.8, -200 + flat)], 2.4, (1, 0.62, 0.5), 0.55 * a)

