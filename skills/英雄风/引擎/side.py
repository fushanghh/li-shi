    hatch(c, [(-80, -440), (-10, -440), (-30, -265), (-120, -270), (-110, -330)], a)
    if armor:
        shape(c, [(-80, -580), (80, -580), (100, -425), (-92, -425)], INKF, 4.5, LINE, a)
