def head_side(c, t, hat='he', beard='none', a=1, hair_tail=True, wind=1.0):
    sw = math.sin(t * 4) * 18 * wind
    # 束发长尾（随风）
    if hair_tail:
        for k, (dy, L) in enumerate(((0, 1.0), (14, 0.8), (-10, 0.7))):
            ex = -60 - 260 * L - sw * (1.4 - 0.3 * k); ey = -900 + dy + 60 * L
            shape(c, [(-52, -935 + dy * 0.3), (-140, -925 + dy, -200 - sw * 0.6, -900 + dy + 30 * L, ex, ey),
                      (-190 - sw * 0.5, -890 + dy + 25 * L, -130, -905 + dy, -56, -915 + dy * 0.3)], HAIR, 2.2, LINE, a)
    # 后脑与头发
    if hat in ('qing', 'turban', 'cap'):
        if hat == 'qing':   # 辫子
            for k in range(9):
                yy = -880 + k * 34; xx = -52 - k * 3 + math.sin(t * 3 + k * 0.5) * 4 * wind * k / 9
                shape(c, [(xx - 13, yy), (xx + 13, yy), (xx + 9, yy + 34), (xx - 9, yy + 34)], HAIR, 2, LINE, a)
        shape(c, [(-10, -838), (-34, -846, -54, -872, -56, -900), (-58, -930), (36, -936), (-10, -920), (-20, -870)], HAIR, 3, LINE, a)
    else:
        shape(c, [(-8, -800), (-40, -805, -66, -840, -66, -880), (-66, -930, -40, -965, 10, -968), (40, -960), (36, -930), (-10, -920), (-20, -870), (-6, -830)], HAIR, 3.5, LINE, a)
    # 侧脸：额、挺鼻、薄唇、方下巴（年轻）
    face = [(-6, -935), (36, -930), (50, -912), (52, -898), (48, -890), (54, -876), (68, -856), (66, -850), (54, -846),
            (57, -836), (52, -830), (55, -820), (50, -808), (44, -796), (20, -788), (-4, -796), (-14, -830), (-18, -880)]
    shape(c, face, SKIN, 4, LINE, a)
    hatch(c, [(-6, -935), (14, -935), (6, -880), (10, -820), (20, -790), (-4, -796), (-14, -830), (-18, -880)], a, gap=7, alpha=0.3)
    # 耳
    shape(c, [(-8, -880), (-20, -885), (-24, -862), (-12, -852)], SKIN, 2.5, LINE, a)
    # 鬓角
    shape(c, [(-10, -925), (6, -920), (0, -870), (-14, -872)], HAIR, 2, LINE, a)
    bc = (0.85, 0.82, 0.78) if beard == 'white' else HAIR
    # 剑眉 + 眼（锐利，看前方）
    shape(c, [(10, -905), (30, -910), (50, -904), (46, -899), (28, -903), (12, -899)], bc, 1.4, LINE, a)
    shape(c, [(26, -888), (40, -892), (49, -886), (38, -882)], (0.95, 0.9, 0.8), 1.4, DARKL, a)
    c.set_source_rgba(*DARKL, a); c.arc(42, -887, 3.4, 0, 6.28); c.fill()
    c.set_source_rgba(1, 1, 1, a); c.arc(43, -888.5, 1.1, 0, 6.28); c.fill()
    line(c, [(24, -878), (40, -876)], 1.2, (0.3, 0.15, 0.08), 0.7 * a)
    # 颧骨、下颌线
    line(c, [(10, -858), (30, -846)], 1.6, (0.3, 0.15, 0.08), a)
    line(c, [(-4, -820), (20, -792)], 1.6, (0.3, 0.15, 0.08), a)
    line(c, [(46, -830), (55, -831)], 2, (0.4, 0.12, 0.08), a)   # 唇线
    if beard == 'white':
        shape(c, [(54, -846), (60, -820, 56, -760, 40, -700), (20, -760, 0, -790, -10, -830), (20, -800), (50, -812)], bc, 2.4, LINE, a)
        for k in range(3): line(c, [(20 + k * 10, -800), (30 + k * 6, -720)], 1.2, (0.5, 0.5, 0.5), 0.7 * a)
    elif beard == 'long':
        shape(c, [(52, -840), (58, -800, 50, -740, 40, -700), (26, -760, 10, -785, 0, -800), (30, -800), (50, -816)], bc, 2.2, LINE, a)
    elif beard == 'grey':
        shape(c, [(52, -840), (58, -800, 50, -740, 40, -700), (26, -760, 10, -785, 0, -800), (30, -800), (50, -816)], (0.62, 0.60, 0.58), 2.2, LINE, a)
        shape(c, [(44, -846), (64, -842), (62, -832), (40, -834)], (0.62, 0.60, 0.58), 1.4, LINE, a)
    elif beard == 'short':
        shape(c, [(54, -846), (58, -820), (50, -800), (30, -792), (40, -812), (52, -826)], bc, 1.6, LINE, a)
    _hat_side(c, hat, t, a)

def _legs_side(c, a, stride, kneel, robe):
    lc = (0.13, 0.10, 0.09)
    if kneel:
        tube(c, [(-10, -150), (-50, -40), (-200, -20)], 66, lc, a)     # 后腿跪地
        shape(c, [(-250, -45), (-180, -45), (-170, 0), (-260, 0)], lc, 4, LINE, a)
        tube(c, [(20, -150), (140, -160), (150, -40)], 70, lc, a)      # 前腿屈膝
        shape(c, [(118, -60), (175, -60), (225, -12), (225, 0), (118, 0)], lc, 4, LINE, a)
        return
    s = stride
    bk = [(-10, -330), (-40 - 40 * s, -170), (-80 - 90 * s, -40)]
    fr = [(20, -330), (60 + 60 * s, -180), (70 + 90 * s, -40)]
    tube(c, bk, 66, lc, a); hatch(c, [(-60, -330), (20, -330), (-60 - 90 * s, -40), (-120 - 90 * s, -40)], a, alpha=0.45)
    shape(c, [(-120 - 90 * s, -60), (-50 - 90 * s, -60), (-20 - 90 * s, -12), (-20 - 90 * s, 0), (-125 - 90 * s, 0)], lc, 4, LINE, a)
    tube(c, fr, 70, lc, a)
    for k in range(3): line(c, [(30 + (40 + 50 * s) * k / 3 - 30, -300 + k * 50), (30 + (40 + 50 * s) * k / 3 + 30, -308 + k * 50)], 1.6, GOLD, 0.6 * a)
    shape(c, [(30 + 90 * s, -60), (100 + 90 * s, -60), (150 + 90 * s, -14), (150 + 90 * s, 0), (30 + 90 * s, 0)], lc, 4, LINE, a)
    line(c, [(36 + 90 * s, -70), (104 + 90 * s, -70)], 2.4, GOLD, a)

